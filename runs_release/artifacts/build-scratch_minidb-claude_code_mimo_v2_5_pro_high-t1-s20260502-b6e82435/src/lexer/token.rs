use std::fmt;

#[derive(Debug, Clone, PartialEq)]
pub enum Token {
    // Literals
    Integer(i64),
    Real(f64),
    StringLit(String),
    BoolLit(bool),
    Null,

    // Identifiers
    Ident(String),

    // Keywords
    Create,
    Table,
    Drop,
    Index,
    On,
    Insert,
    Into,
    Values,
    Select,
    From,
    Where,
    And,
    Or,
    Not,
    Order,
    By,
    Asc,
    Desc,
    Limit,
    Offset,
    Update,
    Set,
    Delete,
    Begin,
    Commit,
    Rollback,
    Primary,
    Key,
    Unique,
    Default,
    Check,
    Is,
    As,
    Inner,
    Join,
    Left,
    Right,
    Cross,
    Outer,
    In,
    Between,
    Like,
    Exists,
    Having,
    Group,
    Count,
    Sum,
    Avg,
    Min,
    Max,
    Distinct,
    All,
    Any,
    Nulls,
    First,
    Last,
    Case,
    When,
    Then,
    Else,
    End,
    If,
    IntType,
    BigIntType,
    RealType,
    TextType,
    BoolType,
    VarcharType,
    CharType,
    FloatType,
    DoubleType,
    IntegerType,
    BooleanType,
    StringType,

    // Symbols
    LParen,
    RParen,
    Comma,
    Semicolon,
    Dot,
    Star,
    Plus,
    Minus,
    Slash,
    Percent,
    Eq,
    Ne,
    Lt,
    Le,
    Gt,
    Ge,
    Concat, // ||

    // Meta
    Eof,
}

impl fmt::Display for Token {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Token::Integer(i) => write!(f, "{}", i),
            Token::Real(r) => write!(f, "{}", r),
            Token::StringLit(s) => write!(f, "'{}'", s),
            Token::BoolLit(b) => write!(f, "{}", b),
            Token::Null => write!(f, "NULL"),
            Token::Ident(s) => write!(f, "{}", s),
            Token::LParen => write!(f, "("),
            Token::RParen => write!(f, ")"),
            Token::Comma => write!(f, ","),
            Token::Semicolon => write!(f, ";"),
            Token::Dot => write!(f, "."),
            Token::Star => write!(f, "*"),
            Token::Plus => write!(f, "+"),
            Token::Minus => write!(f, "-"),
            Token::Slash => write!(f, "/"),
            Token::Percent => write!(f, "%"),
            Token::Eq => write!(f, "="),
            Token::Ne => write!(f, "<>"),
            Token::Lt => write!(f, "<"),
            Token::Le => write!(f, "<="),
            Token::Gt => write!(f, ">"),
            Token::Ge => write!(f, ">="),
            Token::Concat => write!(f, "||"),
            _ => write!(f, "{:?}", self),
        }
    }
}

impl Token {
    pub fn keyword(s: &str) -> Option<Token> {
        match s.to_uppercase().as_str() {
            "CREATE" => Some(Token::Create),
            "TABLE" => Some(Token::Table),
            "DROP" => Some(Token::Drop),
            "INDEX" => Some(Token::Index),
            "ON" => Some(Token::On),
            "INSERT" => Some(Token::Insert),
            "INTO" => Some(Token::Into),
            "VALUES" => Some(Token::Values),
            "SELECT" => Some(Token::Select),
            "FROM" => Some(Token::From),
            "WHERE" => Some(Token::Where),
            "AND" => Some(Token::And),
            "OR" => Some(Token::Or),
            "NOT" => Some(Token::Not),
            "ORDER" => Some(Token::Order),
            "BY" => Some(Token::By),
            "ASC" => Some(Token::Asc),
            "DESC" => Some(Token::Desc),
            "LIMIT" => Some(Token::Limit),
            "OFFSET" => Some(Token::Offset),
            "UPDATE" => Some(Token::Update),
            "SET" => Some(Token::Set),
            "DELETE" => Some(Token::Delete),
            "BEGIN" => Some(Token::Begin),
            "COMMIT" => Some(Token::Commit),
            "ROLLBACK" => Some(Token::Rollback),
            "PRIMARY" => Some(Token::Primary),
            "KEY" => Some(Token::Key),
            "UNIQUE" => Some(Token::Unique),
            "DEFAULT" => Some(Token::Default),
            "CHECK" => Some(Token::Check),
            "IS" => Some(Token::Is),
            "AS" => Some(Token::As),
            "INNER" => Some(Token::Inner),
            "JOIN" => Some(Token::Join),
            "LEFT" => Some(Token::Left),
            "RIGHT" => Some(Token::Right),
            "CROSS" => Some(Token::Cross),
            "OUTER" => Some(Token::Outer),
            "IN" => Some(Token::In),
            "BETWEEN" => Some(Token::Between),
            "LIKE" => Some(Token::Like),
            "EXISTS" => Some(Token::Exists),
            "HAVING" => Some(Token::Having),
            "GROUP" => Some(Token::Group),
            "COUNT" => Some(Token::Count),
            "SUM" => Some(Token::Sum),
            "AVG" => Some(Token::Avg),
            "MIN" => Some(Token::Min),
            "MAX" => Some(Token::Max),
            "DISTINCT" => Some(Token::Distinct),
            "ALL" => Some(Token::All),
            "ANY" => Some(Token::Any),
            "NULLS" => Some(Token::Nulls),
            "FIRST" => Some(Token::First),
            "LAST" => Some(Token::Last),
            "CASE" => Some(Token::Case),
            "WHEN" => Some(Token::When),
            "THEN" => Some(Token::Then),
            "ELSE" => Some(Token::Else),
            "END" => Some(Token::End),
            "IF" => Some(Token::If),
            "INT" | "INTEGER" => Some(Token::IntType),
            "BIGINT" => Some(Token::BigIntType),
            "REAL" => Some(Token::RealType),
            "TEXT" => Some(Token::TextType),
            "BOOL" | "BOOLEAN" => Some(Token::BoolType),
            "VARCHAR" => Some(Token::VarcharType),
            "CHAR" => Some(Token::CharType),
            "FLOAT" => Some(Token::FloatType),
            "DOUBLE" => Some(Token::DoubleType),
            "TRUE" => Some(Token::BoolLit(true)),
            "FALSE" => Some(Token::BoolLit(false)),
            "NULL" => Some(Token::Null),
            _ => None,
        }
    }
}
